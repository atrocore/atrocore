Espo.define('views/entity/fields/is-person', 'views/fields/bool',
    Dep => Dep.extend({

        setup() {
            Dep.prototype.setup.call(this);

            this.listenTo(this.model, 'change:containsPersonalData', () => {
                if (!this.model.get('containsPersonalData')) {
                    this.model.set(this.name, false);
                }
            });
        }
    })
);
